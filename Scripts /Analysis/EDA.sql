-- 6) Ranking (Top N - Bottom N)
-- Order the values of dimensions by measure (Top N Performers | Bottom N Performers)
-- Formula: Rank [Dimension] By AggFunc [Measure] -> Top 5 Products By Total Sales

-- Task: Which 5 products generate the highest revenue? 
SELECT TOP 5
p.product_name,
SUM(f.sales_amount)
FROM Gold.fact_sales f
LEFT JOIN Gold.dim_products p
ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY SUM(f.sales_amount) DESC

-- Solving it using a Window Function (Better for more complex queries)
SELECT
*
FROM
(
	SELECT 
	p.product_name,
	SUM(f.sales_amount) total_revenue,
	ROW_NUMBER() OVER (ORDER BY SUM(f.sales_amount) DESC) AS Rank_Products
	FROM Gold.fact_sales f
	LEFT JOIN Gold.dim_products p
	ON f.product_key = p.product_key
	GROUP BY p.product_name
) t 
WHERE Rank_Products <= 5

-- Task: What are the 5 worst-performing products in terms of sales? 
SELECT TOP 5
p.product_name,
SUM(f.sales_amount)
FROM Gold.fact_sales f
LEFT JOIN Gold.dim_products p
ON f.product_key = p.product_key
GROUP BY p.product_name
ORDER BY SUM(f.sales_amount)

-- Task: Find the top 10 customers who have generated the highest revenue and 3 customers with the fewest orders placed
-- Top 10 cutomers with highest revenue
SELECT TOP 10
CONCAT(c.first_name,' ', c.last_name),
SUM(f.sales_amount)
FROM Gold.fact_sales f
LEFT JOIN Gold.dim_customers c
ON f.customer_key = c.customer_key
GROUP BY CONCAT(c.first_name,' ', c.last_name)
ORDER BY SUM(f.sales_amount) DESC 
-- The 3 customers with the fewest orders placed
SELECT TOP 3
CONCAT(c.first_name,' ', c.last_name),
COUNT(DISTINCT order_number)
FROM Gold.fact_sales f
LEFT JOIN Gold.dim_customers c
ON f.customer_key = c.customer_key
GROUP BY CONCAT(c.first_name,' ', c.last_name)
ORDER BY COUNT(DISTINCT order_number)
